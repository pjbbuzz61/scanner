package scanner.scanner.model.history.hardrock;

public class HardRock_Name {

	private String id;
	private String name;
	private String code;
	private String subCode;
	private HardRock_NameList names;
	
	
	public String getId() {
		return id;
	}
	public void setId(String id) {
		this.id = id;
	}
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public String getCode() {
		return code;
	}
	public void setCode(String code) {
		this.code = code;
	}
	public String getSubCode() {
		return subCode;
	}
	public void setSubCode(String subCode) {
		this.subCode = subCode;
	}
	public HardRock_NameList getNames() {
		return names;
	}
	public void setNames(HardRock_NameList names) {
		this.names = names;
	}

}
